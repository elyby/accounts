    private const int TTL = 600;

    private Altcha $provider;

    protected function setUp(): void {
        parent::setUp();

        // In-memory SET NX: true for a new key, nil for the existing one
        $usedKeys = [];
        $redis = $this->getMockBuilder(Connection::class)->onlyMethods(['executeCommand'])->getMock();
        $redis->method('executeCommand')->willReturnCallback(function(string $command, array $params) use (&$usedKeys): ?bool {
            $this->assertSame('SET', $command);
            if (isset($usedKeys[$params[0]])) {
                return null;
            }

            $usedKeys[$params[0]] = true;

            return true;
        });

        $this->provider = new Altcha(
            altcha: $this->createLibrary(),
            algorithm: new OpensslPbkdf2(),
            usedChallenges: new UsedChallengesStorage($redis),
            cost: 1,
            counterMin: 1,
            counterMax: 10,
            ttl: self::TTL,
        );
    }

    public function testGetPublicParams(): void {
        $this->assertSame(['challengeUrl' => '/api/captcha/altcha/challenge'], $this->provider->getPublicParams());
    }

    public function testCreateChallenge(): void {
        $first = $this->provider->createChallenge();
        $second = $this->provider->createChallenge();

        $this->assertNotSame($first['signature'], $second['signature']);
        $this->assertSame('PBKDF2/SHA-256', $first['parameters']['algorithm']);
        $this->assertArrayHasKey('keySignature', $first['parameters'], 'The fast verification path must be enabled');
        $this->assertEqualsWithDelta(time() + self::TTL, $first['parameters']['expiresAt'], 2);
        $this->assertSame(['counterMax' => 10], $first['parameters']['data']);
    }

    public function testVerifyTamperedData(): void {
        $payload = $this->solve($this->provider->createChallenge());
        $challenge = $payload->challenge->toArray();
        $challenge['parameters']['data'] = ['counterMax' => 1];
        $tampered = new Payload(Challenge::fromArray($challenge), $payload->solution);

        $this->assertFalse($this->provider->verify($tampered->toBase64(), null), 'The data must be signed');
    }

    public function testVerifyValidSolution(): void {
        $this->assertTrue($this->provider->verify($this->solve($this->provider->createChallenge())->toBase64(), null));
    }

    public function testVerifyGoldenPayload(): void {
        $this->assertTrue($this->provider->verify(self::GOLDEN_PAYLOAD, null));
    }

    public function testVerifyReplay(): void {
        $token = $this->solve($this->provider->createChallenge())->toBase64();

        $this->assertTrue($this->provider->verify($token, null));
        $this->assertFalse($this->provider->verify($token, null));
    }

    public function testVerifyReplayWithChangedCounter(): void {
        $payload = $this->solve($this->provider->createChallenge());
        // On the fast path the library doesn't check the counter, so this payload is still valid for it
        $changed = new Payload($payload->challenge, new Solution($payload->solution->counter + 1, $payload->solution->derivedKey));

        $this->assertTrue($this->provider->verify($payload->toBase64(), null));
        $this->assertFalse($this->provider->verify($changed->toBase64(), null));
    }

    public function testVerifyExpired(): void {
        Carbon::setTestNow(Carbon::now()->subSeconds(self::TTL + 10));
        try {
            $challenge = $this->provider->createChallenge();
        } finally {
            Carbon::setTestNow();
        }

        $this->assertFalse($this->provider->verify($this->solve($challenge)->toBase64(), null));
    }

    public function testVerifyChallengeSignedWithAnotherSecret(): void {
        $foreign = new AltchaLib('another-secret-0123456789abcdef01234', self::KEY_SIGNATURE_SECRET);
        $challenge = $foreign->createChallenge(new CreateChallengeOptions(algorithm: new Pbkdf2(), cost: 1, counter: 5, expiresAt: time() + self::TTL));

        $this->assertFalse($this->provider->verify($this->solve($challenge->toArray())->toBase64(), null));
    }

    public function testVerifyTamperedDerivedKey(): void {
        $payload = $this->solve($this->provider->createChallenge());
        $tampered = new Payload($payload->challenge, new Solution($payload->solution->counter, str_repeat('0', 64)));

        $this->assertFalse($this->provider->verify($tampered->toBase64(), null));
    }

    /**
     * @dataProvider noExpirationProvider
     */
    public function testVerifyChallengeWithoutExpiration(?int $expiresAt): void {
        $challenge = $this->createLibrary()->createChallenge(new CreateChallengeOptions(algorithm: new Pbkdf2(), cost: 1, counter: 5, expiresAt: $expiresAt));

        $this->assertFalse($this->provider->verify($this->solve($challenge->toArray())->toBase64(), null));
    }

    /**
     * @return iterable<string, array{int|null}>
     */
    public static function noExpirationProvider(): iterable {
        yield 'missing' => [null];
        yield 'zero' => [0];
    }

    /**
     * @dataProvider malformedTokensProvider
     */
    public function testVerifyMalformedToken(string $token): void {
        $this->assertFalse($this->provider->verify($token, null));
    }

    /**
     * @return iterable<string, array{string}>
     */
    public static function malformedTokensProvider(): iterable {
        yield 'empty string' => [''];
        yield 'not base64' => ['!!!'];
        yield 'not json' => [base64_encode('not json')];
        yield 'json scalar' => [base64_encode('42')];
        yield 'no solution' => [base64_encode('{"challenge":{"parameters":{}}}')];
        yield 'invalid counter' => [base64_encode('{"challenge":{"parameters":{}},"solution":{"counter":"1","derivedKey":"00"}}')];
    }

    private function createLibrary(): AltchaLib {
        return new AltchaLib(self::SIGNATURE_SECRET, self::KEY_SIGNATURE_SECRET);
    }

    /**
     * Solves with the library's own PBKDF2 implementation, which also cross-checks {@see OpensslPbkdf2}
     *
     * @param array<string, mixed> $challenge
     */
    private function solve(array $challenge): Payload {
        $challenge = Challenge::fromArray($challenge);
        $solution = $this->createLibrary()->solveChallenge(new SolveChallengeOptions($challenge, new Pbkdf2()));
        $this->assertNotNull($solution);

        return new Payload($challenge, $solution);
    }

}
